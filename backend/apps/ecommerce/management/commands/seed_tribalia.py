class Command(BaseCommand):
    help = "Puebla los 10 productos oficiales de Tribalia con planes Mensual y Anual"

    def handle(self, *args, **options):
        for item in TRIBALIA_CATALOG:
            product, _ = Product.objects.update_or_create(
                sku=item['sku'],
                defaults={
                    'name': item['name'],
                    'slug': item['slug'],
                    'tagline': item['tagline'],
                    'description': item['description'],
                    'accent_color': item['accent_color'],
                    'bridge_color': item['bridge_color'],
                    'subdomain_url': item['subdomain_url'],
                    'logo_path': item['logo_path'],
                    'display_order': item['order'],
                    'is_active': True,
                },
            )
            LicenseType.objects.get_or_create(
                product=product,
                billing_cycle='monthly',
                defaults={
                    'name': 'Suscripción Mensual',
                    'price': item['monthly_price'],
                    'duration_days': 30,
                    'is_active': True,
                },
            )
            LicenseType.objects.get_or_create(
                product=product,
                billing_cycle='annual',
                defaults={
                    'name': 'Suscripción Anual',
                    'price': item['annual_price'],
                    'duration_days': 365,
                    'is_active': True,
                },
            )
        self.stdout.write(self.style.SUCCESS("Catálogo Tribalia (10 productos x Mensual/Anual) listo."))
